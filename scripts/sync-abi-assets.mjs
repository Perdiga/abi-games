import { mkdir, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

const DATABASE_URL = 'https://perdiga.github.io/abi-assets-database'
const OUTPUT_ROOT = join(process.cwd(), 'public', 'abi-assets')
const GENERATED_CATALOG_PATH = join(process.cwd(), 'src', 'data', 'abi-assets.generated.ts')
const METADATA_ONLY = process.argv.includes('--metadata-only')
const JSON_FILES = [
  'backpacks.json',
  'ballistic_rigs.json',
  'ballistic_vests.json',
  'chest_rigs.json',
  'food.json',
  'headsets.json',
  'helmet_shields.json',
  'helmets.json',
  'keys.json',
  'masks.json',
  'medical.json',
  'pistols.json',
  'throwables.json',
  'varieties.json',
  'weapons.json',
]

const fetchRequired = async (path, { allowMissing = false } = {}) => {
  const response = await fetch(`${DATABASE_URL}/${path}`, { cache: 'no-store' })
  if (allowMissing && response.status === 404) return null
  if (!response.ok) throw new Error(`Could not download ${path}: HTTP ${response.status}`)
  return response
}

const writeAsset = async (relativePath, body) => {
  const outputPath = join(OUTPUT_ROOT, relativePath)
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, body)
}

const exists = async (path) => stat(path).then(() => true).catch(() => false)

const syncImage = async (assetPath) => {
  const outputPath = join(OUTPUT_ROOT, assetPath)
  if (await exists(outputPath)) return false

  const response = await fetchRequired(assetPath, { allowMissing: true })
  if (!response) return null
  await writeAsset(assetPath, Buffer.from(await response.arrayBuffer()))
  return true
}

const mapWithConcurrency = async (values, limit, callback) => {
  let nextIndex = 0
  const workers = Array.from({ length: Math.min(limit, values.length) }, async () => {
    while (nextIndex < values.length) {
      const value = values[nextIndex]
      nextIndex += 1
      await callback(value)
    }
  })
  await Promise.all(workers)
}

const toGeneratedSource = (items) => `// Generated by scripts/sync-abi-assets.mjs. Do not edit manually.\n\nexport interface AbiAssetItem {\n  id: string\n  type: string\n  name: string\n  price: number | null\n  assetPath: string | null\n  widthSlots: number | null\n  heightSlots: number | null\n  widthSlotsOpen: number | null\n  heightSlotsOpen: number | null\n  slots: string | null\n}\n\nexport const abiAssetItems: readonly AbiAssetItem[] = ${JSON.stringify(items, null, 2)}\n\nexport const abiAssetById = Object.fromEntries(abiAssetItems.map((item) => [item.id, item]))\n`

await mkdir(OUTPUT_ROOT, { recursive: true })

const itemGroups = await Promise.all(
  JSON_FILES.map(async (file) => {
    const response = await fetchRequired(file)
    const body = await response.text()
    await writeAsset(file, body)
    const items = JSON.parse(body)
    if (!Array.isArray(items)) throw new Error(`${file} must contain an array`)
    return items
  }),
)

const items = itemGroups.flat().map((item) => ({
  id: String(item.id),
  type: String(item.type),
  name: String(item.name),
  price: typeof item.price === 'number' ? item.price : null,
  assetPath: typeof item.asset_path === 'string' ? `/abi-assets/${item.asset_path}` : null,
  widthSlots: typeof item.width_slots === 'number' ? item.width_slots : null,
  heightSlots: typeof item.height_slots === 'number' ? item.height_slots : null,
  widthSlotsOpen: typeof item.width_slots_open === 'number' ? item.width_slots_open : null,
  heightSlotsOpen: typeof item.height_slots_open === 'number' ? item.height_slots_open : null,
  slots: typeof item.slots === 'string' ? item.slots : null,
}))

await mkdir(dirname(GENERATED_CATALOG_PATH), { recursive: true })

if (METADATA_ONLY) {
  await writeFile(GENERATED_CATALOG_PATH, toGeneratedSource(items))
  console.log(`Synced metadata for ${items.length} ABI assets.`)
  process.exit(0)
}

const imagePaths = [...new Set(items.map((item) => item.assetPath?.replace('/abi-assets/', '')).filter(Boolean))]
let downloadedImages = 0
const missingImages = new Set()
console.log(`Syncing ${imagePaths.length} ABI asset images…`)
await mapWithConcurrency(imagePaths, 12, async (assetPath) => {
  const downloaded = await syncImage(assetPath)
  if (downloaded === null) {
    missingImages.add(assetPath)
    console.warn(`Image not found upstream (HTTP 404): ${assetPath}; using the default item icon.`)
  } else if (downloaded) {
    downloadedImages += 1
    if (downloadedImages % 10 === 0) console.log(`Downloaded ${downloadedImages} new images…`)
  }
})

const syncedItems = items.map((item) => (
  missingImages.has(item.assetPath?.replace('/abi-assets/', '')) ? { ...item, assetPath: null } : item
))
await writeFile(GENERATED_CATALOG_PATH, toGeneratedSource(syncedItems))

console.log(`Synced ${items.length} ABI assets and downloaded ${downloadedImages} new images.`)
if (missingImages.size > 0) console.warn(`${missingImages.size} images are unavailable upstream; their items use default icons.`)
